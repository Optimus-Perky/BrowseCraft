"""BrowseCraft: the light update check, the update tab and the "What's new" tab (13 Nov 2026).

- Update check: shortly after start-up and then once a day, a plain GET of latest.json (no
  cookies, no identifiers) from the download site. A newer version shows quietly in the app menu
  and on Settings > About. A security update also opens chrome://browsecraft/update: at the
  first start of the day, at most once a day, never mid-session; "Skip this version" silences that
  version (the next one, a letter release included, shows again). Nothing is ever downloaded or
  installed. Off: the setting on chrome://browsecraft, policy UpdateCheckEnabled = 0, or
  --disable-browsecraft-update-check. Policy UpdateCheckUrl / --browsecraft-update-url point it
  elsewhere (an organisation's own copy, a test file).
- What's new: at the first start after the version changes (not on a fresh install or a
  downgrade), chrome://browsecraft/whatsnew shows the release notes of every version since the
  last one run, bundled in the build (build/release_notes.py, run by version.py stamp).
- Room for "Install updates automatically": the checker only finds versions and tells observers;
  latest.json carries each platform's installer URL and sha256.

New files are in updatecheck/ next to this script. Run in the src tree after profile.py (it edits
the chrome://browsecraft page profile.py writes) and before version.py stamp."""
