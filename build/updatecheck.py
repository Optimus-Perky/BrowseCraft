# The About page's styles: plain CSS, appended.
CSS_FILE = "chrome/browser/resources/settings/about_page/about_page.css"
CSS_RULE = ("\n/* BrowseCraft: a newer version */\n.bc-hidden {\n  display: none;\n}\n\n"
            ".bc-security {\n  color: var(--cr-fallback-color-error, #b3261e);\n  font-weight: 500;\n}\n")


def main():
    failed = False
    for rel in NEW_FILES:
        os.makedirs(os.path.dirname(rel), exist_ok=True)
        shutil.copyfile(os.path.join(HERE, "updatecheck", rel), rel)
    path, text = NOTES_PLACEHOLDER
    if not os.path.exists(path):
        open(path, "w").write(text)
    for path, edits in EDITS.items():
        try:
            text = open(path, encoding="utf-8").read()
        except OSError as e:
            print(f"updatecheck.py: {path}: {e}", file=sys.stderr)
            failed = True
            continue
        for old, new in edits:
            if new in text:
                continue  # already applied
            n = text.count(old)
            if n != 1:
                print(f"updatecheck.py: {path}: expected one match, found {n}: {old[:70]!r}", file=sys.stderr)
                failed = True
                continue
            text = text.replace(old, new, 1)
        open(path, "w", encoding="utf-8").write(text)
    css = open(CSS_FILE, encoding="utf-8").read()
    if CSS_RULE not in css:
        open(CSS_FILE, "a", encoding="utf-8").write(CSS_RULE)
    if failed:
        sys.exit(1)
    print("updatecheck.py: update check, update tab and what's new applied")


if __name__ == "__main__":
    main()
